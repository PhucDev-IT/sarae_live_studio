"""Regenerable video frames. No database state, network access, or GPU decoding."""
from __future__ import annotations

import math
import os
import re
import shutil
import stat
import subprocess
import sys
import time
from pathlib import Path
from typing import BinaryIO

# Existing Agent dependencies; preload with the service, before IPC reads stdin.
# Never import these DLLs for the first time inside a request worker on Windows.
import cv2
import numpy as np

from .models import StudioError, identifier

MAX_JPEG_BYTES = 2 * 1024 * 1024
THUMBNAIL_TIMEOUT = 20


def cache_name(media_id: str, sha256: str) -> str:
    media_id = identifier(media_id)
    if not isinstance(sha256, str) or not re.fullmatch(r"[0-9a-f]{64}", sha256):
        raise StudioError("UNSAFE_PATH", "Invalid managed video digest.")
    return f"{media_id}-{sha256}.jpg"


def cache_dir(root: Path, *, create: bool = False) -> Path:
    """Check each ancestor before creating anything; never follow a junction."""
    for folder in (root, root / "thumbnails", root / "thumbnails" / "media"):
        if (folder.is_symlink() or getattr(folder, "is_junction", lambda: False)()
                or folder.resolve() != folder):
            raise StudioError("UNSAFE_PATH", "Unsafe media thumbnail directory.")
        if create:
            folder.mkdir(exist_ok=True)
        if folder.exists() and not folder.is_dir():
            raise StudioError("UNSAFE_PATH", "Invalid media thumbnail directory.")
    return root / "thumbnails" / "media"


def checked_path(root: Path, name: str) -> Path:
    # Both published and staging names are generated by this module/service.
    if not (re.fullmatch(r"[0-9a-f-]{36}-[0-9a-f]{64}\.jpg", name)
            or re.fullmatch(r"\.frame-[a-z0-9_]+\.jpg", name)):
        raise StudioError("UNSAFE_PATH", "Invalid media thumbnail name.")
    target = cache_dir(root) / name
    if (target.is_symlink() or target.resolve() != target
            or getattr(target, "is_junction", lambda: False)()):
        raise StudioError("UNSAFE_PATH", "Unsafe media thumbnail path.")
    if target.exists():
        info = target.stat()
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise StudioError("UNSAFE_PATH", "Media thumbnails must be regular managed files.")
    return target


def _jpeg_dimensions(data: bytes) -> tuple[int, int] | None:
    """Read SOF/SOS headers without loading an image decoder in IPC workers."""
    if not data.startswith(b"\xff\xd8"):
        return None
    offset = 2
    dimensions = None
    while offset + 4 <= len(data):
        if data[offset] != 0xFF:
            return None
        while offset < len(data) and data[offset] == 0xFF:
            offset += 1
        if offset + 3 > len(data):
            return None
        marker = data[offset]
        length = int.from_bytes(data[offset + 1:offset + 3], "big")
        if length < 2 or offset + 1 + length > len(data):
            return None
        if marker in {0xC0, 0xC1, 0xC2} and length >= 8:
            height = int.from_bytes(data[offset + 4:offset + 6], "big")
            width = int.from_bytes(data[offset + 6:offset + 8], "big")
            components = data[offset + 8]
            if (not 0 < width <= 640 or not 0 < height <= 640
                    or components not in {1, 3} or length != 8 + 3 * components
                    or data[offset + 3] != 8):
                return None
            dimensions = (width, height)
        if marker == 0xDA:
            components = data[offset + 3] if length >= 6 else 0
            return dimensions if components in {1, 3} and length == 6 + 2 * components else None
        offset += 1 + length
    return None


def valid_jpeg(path: Path, *, decode: bool = False) -> bool:
    try:
        if not path.is_file() or not 0 < path.stat().st_size <= MAX_JPEG_BYTES:
            return False
        with path.open("rb") as incoming:
            header = incoming.read(65536)
            incoming.seek(-2, os.SEEK_END)
            end = incoming.read(2)
            dimensions = _jpeg_dimensions(header)
            if end != b"\xff\xd9" or dimensions is None:
                return False
            if not decode:
                return True
            incoming.seek(0)
            data = incoming.read(MAX_JPEG_BYTES + 1)
        if len(data) > MAX_JPEG_BYTES:
            return False
        image = cv2.imdecode(np.frombuffer(data, dtype=np.uint8), cv2.IMREAD_COLOR)
        return image is not None and (image.shape[1], image.shape[0]) == dimensions
    except (OSError, cv2.error):
        return False


def _executable(candidate: str | Path | None) -> str | None:
    if not candidate or "\x00" in str(candidate):
        return None
    path = Path(candidate)
    # Environment overrides are a single local executable, never shell text,
    # relative paths, UNC shares or Windows command scripts.
    if not path.is_absolute() or str(path).startswith(("\\\\", "//")):
        return None
    if os.name == "nt" and path.suffix.lower() != ".exe":
        return None
    try:
        return str(path) if path.is_file() and os.access(path, os.X_OK) else None
    except OSError:
        return None


def resolve_ffmpeg() -> str:
    name = "ffmpeg.exe" if os.name == "nt" else "ffmpeg"
    if getattr(sys, "frozen", False):
        folders = [Path(sys.executable).parent]
        if getattr(sys, "_MEIPASS", None):
            folders.insert(0, Path(sys._MEIPASS))
        for folder in folders:
            if executable := _executable(folder / name):
                return executable
    executable = (_executable(os.environ.get("SARAE_FFMPEG"))
                  or _executable(shutil.which("ffmpeg")))
    if not executable:
        raise StudioError("FFMPEG_UNAVAILABLE", "FFmpeg is required to create video thumbnails. Install FFmpeg and retry.")
    return executable


def generate_frame(source: Path, output: BinaryIO, allowed: set[str], duration: float | None) -> None:
    """Write one JPEG to an already open staging file, within a total 20s budget."""
    executable = resolve_ffmpeg()
    seek = min(duration * 0.1, 1.0) if duration and math.isfinite(duration) and duration > 0 else 0.0
    deadline = time.monotonic() + THUMBNAIL_TIMEOUT
    for position in ([seek, 0.0] if seek else [0.0]):
        output.seek(0)
        output.truncate()
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break
        try:
            result = subprocess.run(
                [executable, "-hide_banner", "-loglevel", "error", "-nostdin",
                 "-protocol_whitelist", "file", "-format_whitelist", ",".join(sorted(allowed)),
                 "-hwaccel", "none", "-threads", "1", "-ss", str(position), "-i", str(source),
                 "-map", "0:v:0", "-frames:v", "1", "-an", "-sn", "-dn",
                 "-vf", "scale=w='max(1,round(640*min(dar,1)))':h='max(1,round(640/max(dar,1)))',setsar=1",
                 "-filter_threads", "1", "-threads", "1", "-c:v", "mjpeg", "-q:v", "3",
                 "-f", "image2pipe", "pipe:1"],
                stdin=subprocess.DEVNULL, stdout=output, stderr=subprocess.DEVNULL,
                timeout=remaining, check=False, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
            )
            output.flush()
            if result.returncode == 0 and valid_jpeg(Path(output.name), decode=True):
                return
        except FileNotFoundError as exc:
            raise StudioError("FFMPEG_UNAVAILABLE", "FFmpeg is unavailable. Install FFmpeg and retry.") from exc
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise StudioError("THUMBNAIL_FAILED", "Could not decode a video thumbnail. Retry after checking FFmpeg and the video.") from exc
    raise StudioError("THUMBNAIL_FAILED", "FFmpeg could not decode a video thumbnail. You can retry.")
